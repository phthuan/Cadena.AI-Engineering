
# Dong bo Skills va khoi quy tac dung chung vao ~/.claude.
# Luu y: giu file nay chi gom ky tu ASCII (tieng Viet khong dau). PowerShell 5.1 doc file
# .ps1 khong co BOM theo codepage ANSI, nen ky tu co dau se bi hong.

$ErrorActionPreference = "Stop"

$repo = Split-Path -Parent $PSScriptRoot
$sourceSkills = Join-Path $repo "skills"
$targetSkills = Join-Path $env:USERPROFILE ".claude\skills"

if (!(Test-Path $sourceSkills -PathType Container)) {
    throw "Khong tim thay thu muc skills nguon: $sourceSkills"
}

New-Item -ItemType Directory -Force -Path $targetSkills |
    Out-Null

function Get-NormalizedPath([string]$Path) {
    return [System.IO.Path]::GetFullPath($Path).TrimEnd('\')
}

$sourceRoot = Get-NormalizedPath $sourceSkills

# Chi nhung thu muc co SKILL.md moi la skill nguon hop le.
$validSources = @{}

Get-ChildItem $sourceSkills -Directory | ForEach-Object {
    $source = Get-NormalizedPath $_.FullName

    if (Test-Path (Join-Path $source "SKILL.md") -PathType Leaf) {
        $validSources[$source] = $true
    }
}

# Chi xoa cac Junction cu (stale) tro truc tiep vao thu muc skills cua repo nay.
# Giu nguyen thu muc thuong va cac Junction tro toi vi tri khac.
Get-ChildItem $targetSkills -Force | ForEach-Object {
    $target = $_.FullName
    $item = Get-Item $target -Force

    if ($item.LinkType -ne "Junction") {
        return
    }

    foreach ($linkTarget in @($item.Target)) {
        if ([string]::IsNullOrWhiteSpace($linkTarget)) {
            continue
        }

        $normalizedTarget = Get-NormalizedPath $linkTarget
        $parent = [System.IO.Path]::GetDirectoryName($normalizedTarget)

        # Phai tro toi thu muc con truc tiep cua thu muc skills trong repo nay.
        if (!$parent -or
            ![string]::Equals(
                (Get-NormalizedPath $parent),
                $sourceRoot,
                [System.StringComparison]::OrdinalIgnoreCase
            )) {
            continue
        }

        if (!$validSources.ContainsKey($normalizedTarget)) {
            Write-Host "Xoa Junction cu: $($_.Name)"

            # Chi xoa ban than Junction, khong xoa thu muc nguon.
            & cmd.exe /d /c rmdir $target

            if ($LASTEXITCODE -ne 0) {
                throw "Khong xoa duoc Junction: $target"
            }
        }
    }
}

# Tao Junction con thieu cho cac skill nguon hop le.
Get-ChildItem $sourceSkills -Directory | ForEach-Object {
    $name = $_.Name
    $source = $_.FullName
    $target = Join-Path $targetSkills $name

    if (!(Test-Path (Join-Path $source "SKILL.md") -PathType Leaf)) {
        Write-Host "Bo qua (thieu SKILL.md): $name"
        return
    }

    if (Test-Path $target) {
        $item = Get-Item $target -Force
        $normalizedSource = Get-NormalizedPath $source

        if ($item.LinkType -eq "Junction" -and
            @($item.Target | ForEach-Object {
                Get-NormalizedPath $_
            }) -contains $normalizedSource) {
            Write-Host "Da lien ket: $name"
        }
        else {
            Write-Warning "Giu nguyen duong dan da ton tai: $target"
        }

        return
    }

    New-Item -ItemType Junction -Path $target -Target $source |
        Out-Null

    Write-Host "Da tao lien ket: $name"
}

# Ghi khoi quy tac dung chung vao CLAUDE.md global, kem duong dan repo tren may nay.
# Chi phan nam giua hai marker duoc quan ly; moi noi dung ben ngoai duoc giu nguyen.
# KHONG doi chuoi $beginMarker / $endMarker: neu doi, khoi cu se khong duoc nhan ra
# va mot khoi moi se bi them vao lan nua.
$template = Join-Path $PSScriptRoot "claude-global.template.md"
$globalClaude = Join-Path $env:USERPROFILE ".claude\CLAUDE.md"
$beginMarker = "<!-- BEGIN Cadena.AI-Engineering (generated by scripts/sync-skills.ps1, do not edit) -->"
$endMarker = "<!-- END Cadena.AI-Engineering -->"

if (!(Test-Path $template -PathType Leaf)) {
    throw "Khong tim thay template: $template"
}

# Template duoc doc dang UTF-8 nen co the chua tieng Viet co dau.
$skillList = ($validSources.Keys |
    ForEach-Object { "- " + (Split-Path -Leaf $_) } |
    Sort-Object) -join "`n"

$body = ([System.IO.File]::ReadAllText($template) -replace "`r`n", "`n").Trim()
$body = $body.Replace("{{REPO}}", (Get-NormalizedPath $repo)).Replace("{{SKILLS}}", $skillList)
$block = "$beginMarker`n$body`n$endMarker"

$existing = ""
if (Test-Path $globalClaude -PathType Leaf) {
    $existing = [System.IO.File]::ReadAllText($globalClaude)
}

$pattern = "(?s)" + [regex]::Escape($beginMarker) + ".*?" + [regex]::Escape($endMarker)

if ($existing -match $pattern) {
    # Dung MatchEvaluator de ky tu "$" trong duong dan khong bi hieu la substitution.
    $updated = [regex]::Replace($existing, $pattern, { param($m) $block })
}
elseif ([string]::IsNullOrWhiteSpace($existing)) {
    $updated = "$block`n"
}
else {
    $updated = $existing.TrimEnd() + "`n`n$block`n"
}

if ($updated -ne $existing) {
    [System.IO.File]::WriteAllText($globalClaude, $updated, (New-Object System.Text.UTF8Encoding $false))
    Write-Host "Da cap nhat: $globalClaude"
}
else {
    Write-Host "Da moi nhat, khong can cap nhat: $globalClaude"
}
